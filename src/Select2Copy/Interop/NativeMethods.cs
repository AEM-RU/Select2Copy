    public static bool KeyDown(int vk)
    {
        return (GetAsyncKeyState(vk) & 0x8000) != 0;
    }

    public static IntPtr LParam(int x, int y)
    {
        return new IntPtr(((short)y << 16) | ((short)x & 0xFFFF));
    }

    public static void RoundCorners(IntPtr hwnd)
    {
        int value = DWMWCP_ROUND;
        try
        {
            DwmSetWindowAttribute(hwnd, DWMWA_WINDOW_CORNER_PREFERENCE, ref value, sizeof(int));
        }
        catch
        {
        }
    }
